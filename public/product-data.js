// Helper function to get full product data
window.getFullProductData = function (productId) {
    // Try to find the product in allStoreProducts or MOCK_PRODUCTS
    const baseProduct = window.allStoreProducts?.find(p => p._id == productId || p.id == productId) ||
        (window.MOCK_PRODUCTS && window.MOCK_PRODUCTS.find(p => p._id == productId || p.id == productId));

    if (!baseProduct) {
        console.error('Product not found with ID:', productId);
        return null;
    }

    // Get extension data if available
    const extension = PRODUCT_EXTENSIONS[productId] || {};

    // Create default features if not available
    const defaultFeatures = [
        'منتج عالي الجودة',
        'مناسب للاستخدام اليومي',
        'ضمان الجودة',
        'شحن سريع'
    ];

    const defaultFeaturesEn = [
        'High quality product',
        'Suitable for daily use',
        'Quality guarantee',
        'Fast shipping'
    ];

    return {
        ...baseProduct,
        ...extension,
        images: extension.images || (baseProduct.images && baseProduct.images.length > 0 ? baseProduct.images : [baseProduct.image]),
        rating: extension.rating || baseProduct.rating || 4.0,
        reviews: extension.reviews || baseProduct.reviews || 0,
        stock: extension.stock || baseProduct.stock || 10,
        detailedDescription: extension.detailedDescription || baseProduct.detailedDescription || baseProduct.description || 'منتج رائع بجودة عالية',
        detailedDescriptionEn: extension.detailedDescriptionEn || baseProduct.detailedDescriptionEn || baseProduct.descriptionEn || 'Great product with high quality',
        features: extension.features || baseProduct.features || defaultFeatures,
        featuresEn: extension.featuresEn || baseProduct.featuresEn || defaultFeaturesEn
    };
};

